const CELL_SIZE = 48;

const createLight = (overrides: Partial<LightSource> = {}): LightSource => ({
  position: { x: 1, y: 2 },
  alignment: CellAlignment.CENTER,
  color: '#FFB85C',
  radius: 4,
  intensity: 0.35,
  softness: 0,
  enabled: true,
  ...overrides,
});

const createHeroAt = (x: number, y: number, health = 6): Hero => ({
  name: 'Fearik',
  actions: 2,
  movement: 4,
  maxMovement: 4,
  defense: 2,
  health,
  maxHealth: 6,
  colour: Colour.Red,
  experience: 0,
  position: { x, y },
  level: Level.APPRENTICE,
  weapon: weapons[0],
  inventory: [],
  isInventoryOpen: false,
});

const createMonsterAt = (x: number, y: number, health = 2): Monster => ({
  name: 'Orc (Green)',
  type: MonsterType.ORC,
  actions: 2,
  movement: 4,
  maxMovement: 4,
  defense: 1,
  health,
  maxHealth: 2,
  colour: Colour.Green,
  experience: 1,
  position: { x, y },
  level: Level.APPRENTICE,
  weapon: monsterWeapons[0],
  inventory: [],
});

const createState = (
  overrides: {
    grid?: string[];
    doors?: GameState['dungeon']['layout']['doors'];
    pillars?: { x: number; y: number }[];
    monsters?: Monster[];
    heroes?: Hero[];
    discoveredRooms?: string[];
  } = {},
): GameState => ({
  dungeon: {
    name: 'Light Test Dungeon',
    intro: 'test-dungeon',
    discoveredRooms: overrides.discoveredRooms ?? ['A'],
    layout: {
      grid: overrides.grid ?? [
        '#######',
        '#AAAAA#',
        '#AAAAA#',
        '#AAAAA#',
        '#######',
      ],
      doors: overrides.doors ?? [],
      monsters: overrides.monsters ?? [],
      secrets: [],
      notes: [],
      items: [],
      corridors: [],
      pillars: overrides.pillars ?? [],
      pits: [],
      corners: [],
    },
    startingPositions: [{ x: 1, y: 1 }],
    winConditions: [],
    beaten: false,
    killCount: 0,
  },
  heroes: overrides.heroes ?? [createHeroAt(1, 3)],
  currentActor: undefined,
  actionLog: [],
  itemDeck: [],
  magicItemDeck: [],
  settings: { cellSize: CELL_SIZE },
  eventDeck: [],
  reRender: false,
  drawEvents: true,
});

// Finds the polygon point generated by the ray closest to the given angle.
const rayEndpoint = (points: { x: number; y: number }[], angle: number) => {
  const rayCount = points.length;
  const index =
    ((Math.round((angle / (2 * Math.PI)) * rayCount) % rayCount) + rayCount) %
    rayCount;
  return points[index];
};

describe('lightCenter', () => {
  it('places the light at the center by default', () => {
    expect(lightCenter(createLight(), CELL_SIZE)).toEqual({
      x: 1.5 * CELL_SIZE,
      y: 2.5 * CELL_SIZE,
    });
  });

  it('centers a ceiling light on its cell like a center light', () => {
    const light = createLight({
      position: { x: 1, y: 2 },
      alignment: CellAlignment.CEILING,
    });
    expect(lightCenter(light, CELL_SIZE)).toEqual({
      x: 1.5 * CELL_SIZE,
      y: 2.5 * CELL_SIZE,
    });
  });

  it('insets corner alignments into the cell', () => {
    const cell = { x: 1, y: 2 };
    const inset = CELL_SIZE * 0.25;
    expect(
      lightCenter(
        createLight({ ...cell, alignment: CellAlignment.TOP_LEFT }),
        CELL_SIZE,
      ),
    ).toEqual({ x: cell.x * CELL_SIZE + inset, y: cell.y * CELL_SIZE + inset });
    expect(
      lightCenter(
        createLight({ ...cell, alignment: CellAlignment.TOP_RIGHT }),
        CELL_SIZE,
      ),
    ).toEqual({
      x: (cell.x + 1) * CELL_SIZE - inset,
      y: cell.y * CELL_SIZE + inset,
    });
    expect(
      lightCenter(
        createLight({ ...cell, alignment: CellAlignment.BOTTOM_LEFT }),
        CELL_SIZE,
      ),
    ).toEqual({
      x: cell.x * CELL_SIZE + inset,
      y: (cell.y + 1) * CELL_SIZE - inset,
    });
    expect(
      lightCenter(
        createLight({ ...cell, alignment: CellAlignment.BOTTOM_RIGHT }),
        CELL_SIZE,
      ),
    ).toEqual({
      x: (cell.x + 1) * CELL_SIZE - inset,
      y: (cell.y + 1) * CELL_SIZE - inset,
    });
  });
});

describe('lightBlockInCell', () => {
  it('marks walls and pillars as opaque so they get lit themselves', () => {
    const state = createState({ pillars: [{ x: 2, y: 3 }] });
    const light = createLight({ position: { x: 1, y: 2 } });
    expect(lightBlockInCell(state, { x: 0, y: 2 }, light, false)).toBe(
      'opaque',
    );
    expect(lightBlockInCell(state, { x: 2, y: 3 }, light, false)).toBe(
      'opaque',
    );
    // Out-of-grid cells are fog: nothing to light beyond the dungeon.
    expect(lightBlockInCell(state, { x: -1, y: 2 }, light, false)).toBe('fog');
  });

  it('marks undiscovered cells as fog outside debug mode only', () => {
    const grid = ['#######', '#AAAAA#', '#ABBBB#', '#ABBBB#', '#######'];
    const state = createState({ grid, discoveredRooms: ['A'] });
    const light = createLight({ position: { x: 1, y: 2 } });
    expect(lightBlockInCell(state, { x: 2, y: 2 }, light, false)).toBe('fog');
    expect(lightBlockInCell(state, { x: 2, y: 2 }, light, true)).toBe('none');
  });

  it('marks alive actors as opaque but not dead ones, and not the light own cell', () => {
    const state = createState({
      monsters: [createMonsterAt(3, 2)],
      heroes: [createHeroAt(2, 2, 0)],
    });
    const light = createLight({ position: { x: 1, y: 2 } });
    expect(lightBlockInCell(state, { x: 3, y: 2 }, light, false)).toBe(
      'opaque',
    );
    expect(lightBlockInCell(state, { x: 2, y: 2 }, light, false)).toBe('none');
    // An actor standing on the light's own cell does not block it.
    const stateOnLight = createState({ monsters: [createMonsterAt(1, 2)] });
    expect(
      lightBlockInCell(
        stateOnLight,
        { x: 1, y: 2 },
        createLight({ position: { x: 1, y: 2 } }),
        false,
      ),
    ).toBe('none');
  });

  it('treats actors as transparent for ceiling lights', () => {
    const state = createState({ monsters: [createMonsterAt(3, 2)] });
    const ceilingLight = createLight({
      position: { x: 1, y: 2 },
      alignment: CellAlignment.CEILING,
    });
    // Actors neither block nor shadow a ceiling light...
    expect(lightBlockInCell(state, { x: 3, y: 2 }, ceilingLight, false)).toBe(
      'none',
    );
    // ...but walls and pillars still do.
    expect(lightBlockInCell(state, { x: 0, y: 2 }, ceilingLight, false)).toBe(
      'opaque',
    );
  });
});

describe('computeLightPolygon', () => {
  it('extends to the radius in an open area', () => {
    const state = createState({
      grid: ['#########', '#AAAAAAA#', '#AAAAAAA#', '#AAAAAAA#', '#########'],
      heroes: [],
    });
    const light = createLight({ position: { x: 3, y: 2 }, radius: 1.5 });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    const center = lightCenter(light, CELL_SIZE);
    points.forEach((point) => {
      const distance = Math.hypot(point.x - center.x, point.y - center.y);
      // Rays end within one marching step of the radius.
      expect(distance).toBeGreaterThan(1.5 * CELL_SIZE - CELL_SIZE / 6 - 1);
      expect(distance).toBeLessThanOrEqual(1.5 * CELL_SIZE + 1);
    });
  });

  it('illuminates walls only partway into the wall cell', () => {
    const state = createState();
    const light = createLight({ position: { x: 3, y: 2 }, radius: 10 });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    // Ray to the right: wall column x=6 is lit halfway into the cell, so
    // light never looks like it passes through the whole wall.
    expect(rayEndpoint(points, 0).x).toBeCloseTo(6.5 * CELL_SIZE, 0);
    // Ray to the left: halfway into wall column x=0.
    expect(rayEndpoint(points, Math.PI).x).toBeCloseTo(0.5 * CELL_SIZE, 0);
    // Straight up: halfway into wall row y=0.
    expect(rayEndpoint(points, -Math.PI / 2).y).toBeCloseTo(0.5 * CELL_SIZE, 0);
  });

  it('illuminates pillars only partway into the cell', () => {
    const state = createState({ pillars: [{ x: 4, y: 2 }] });
    const light = createLight({ position: { x: 2, y: 2 }, radius: 10 });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    expect(rayEndpoint(points, 0).x).toBeCloseTo(4.5 * CELL_SIZE, 0);
  });

  it('stops at closed doors but passes open ones', () => {
    const closedDoorState = createState({
      doors: [
        {
          x: 3,
          y: 2,
          side: Side.RIGHT,
          locked: false,
          trapped: false,
          open: false,
          hidden: false,
          trapAttacks: 0,
          reinforced: false,
        },
      ],
    });
    const light = createLight({ position: { x: 2, y: 2 }, radius: 10 });
    const closedPoints = computeLightPolygon(
      light,
      closedDoorState,
      CELL_SIZE,
      false,
    );
    // Door edge between (3,2) and (4,2): light stops at x=4.
    expect(rayEndpoint(closedPoints, 0).x).toBeCloseTo(4 * CELL_SIZE, 0);

    const openDoorState = createState({
      doors: [
        {
          x: 3,
          y: 2,
          side: Side.RIGHT,
          locked: false,
          trapped: false,
          open: true,
          hidden: false,
          trapAttacks: 0,
          reinforced: false,
        },
      ],
    });
    const openPoints = computeLightPolygon(
      light,
      openDoorState,
      CELL_SIZE,
      false,
    );
    // Light passes the open door and reaches halfway into the far wall.
    expect(rayEndpoint(openPoints, 0).x).toBeCloseTo(6.5 * CELL_SIZE, 0);
  });

  it('illuminates the actor sprite and casts a shadow behind it', () => {
    const state = createState({ monsters: [createMonsterAt(4, 2)] });
    const light = createLight({ position: { x: 2, y: 2 }, radius: 10 });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    // The monster's cell is lit partway in — enough for the sprite, which
    // sits near the middle of the cell — and the shadow starts behind it.
    expect(rayEndpoint(points, 0).x).toBeCloseTo(4.5 * CELL_SIZE, 0);
  });

  it('lets ceiling light pass through actors without shadows', () => {
    const state = createState({ monsters: [createMonsterAt(4, 2)] });
    const light = createLight({
      position: { x: 2, y: 2 },
      radius: 10,
      alignment: CellAlignment.CEILING,
    });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    // The monster is lit from above and casts no shadow: the ray runs
    // through its cell and on to the wall.
    expect(rayEndpoint(points, 0).x).toBeCloseTo(6.5 * CELL_SIZE, 0);
  });

  it('passes light between two diagonally adjacent actors', () => {
    const state = createState({
      monsters: [createMonsterAt(3, 1), createMonsterAt(4, 2)],
    });
    const light = createLight({ position: { x: 2, y: 2 }, radius: 10 });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    // The ray through the shared corner of the two actors travels via the
    // empty flanking cells and keeps going: actors do not fill their cells.
    const throughGap = rayEndpoint(points, Math.atan2(-1, 3));
    expect(throughGap.x).toBeGreaterThan(5 * CELL_SIZE);
    // It only ends at the far wall column, halfway into the wall.
    expect(throughGap.x).toBeCloseTo(6.5 * CELL_SIZE, 0);
  });

  it('stops at undiscovered cells outside debug mode', () => {
    const grid = ['#######', '#AAAAA#', '#ABBBB#', '#ABBBB#', '#######'];
    const state = createState({ grid, discoveredRooms: ['A'], heroes: [] });
    const light = createLight({ position: { x: 1, y: 2 }, radius: 10 });
    const points = computeLightPolygon(light, state, CELL_SIZE, false);
    // Ray to the right hits undiscovered room B at (2,2): stops at edge x=2.
    expect(rayEndpoint(points, 0).x).toBeCloseTo(2 * CELL_SIZE, 0);
    // Ray straight down stays inside discovered room A; the wall row y=4
    // is lit partway into the wall cell.
    expect(rayEndpoint(points, Math.PI / 2).y).toBeCloseTo(4.5 * CELL_SIZE, 0);

    // In debug mode the fog is ignored, but the far wall still ends the ray.
    const debugPoints = computeLightPolygon(light, state, CELL_SIZE, true);
    expect(rayEndpoint(debugPoints, 0).x).toBeCloseTo(6.5 * CELL_SIZE, 0);
  });
});

describe('renderLights', () => {
  const createMockCtx = (gradient?: {
    addColorStop: ReturnType<typeof vi.fn>;
  }) =>
    ({
      createRadialGradient: vi
        .fn()
        .mockReturnValue(gradient ?? { addColorStop: vi.fn() }),
      save: vi.fn(),
      restore: vi.fn(),
      beginPath: vi.fn(),
      moveTo: vi.fn(),
      lineTo: vi.fn(),
      closePath: vi.fn(),
      fill: vi.fn(),
      arc: vi.fn(),
      stroke: vi.fn(),
      drawImage: vi.fn(),
      setTransform: vi.fn(),
      clearRect: vi.fn(),
      fillRect: vi.fn(),
    }) as unknown as CanvasRenderingContext2D;

  it('renders a discovered light with a single smooth radial gradient', () => {
    const state = createState();
    state.dungeon.layout.lights = [createLight()];
    const addColorStop = vi.fn();
    const ctx = createMockCtx({ addColorStop });
    renderLights(ctx, CELL_SIZE, state, false);
    expect(ctx.createRadialGradient).toHaveBeenCalledTimes(1);
    expect(ctx.fill).toHaveBeenCalled();

    // One continuous falloff: alpha decreases monotonically from the bright
    // source to transparent at the radius, with no step that would show up
    // as a ring around the center.
    const stops = addColorStop.mock.calls.map(
      (call: [number, string]) => call[0],
    );
    expect(stops[0]).toBe(0);
    expect(stops[stops.length - 1]).toBe(1);
    expect(new Set(stops).size).toBe(stops.length);
    const alphas = addColorStop.mock.calls.map((call: [number, string]) => {
      const match = call[1].match(/([\d.]+)\)$/);
      expect(match).not.toBeNull();
      return Number(match![1]);
    });
    alphas.forEach((alpha, i) => {
      if (i > 0) {
        expect(alpha).toBeLessThan(alphas[i - 1]);
      }
    });
    expect(alphas[alphas.length - 1]).toBe(0);
  });

  it('skips lights on undiscovered cells and disabled lights', () => {
    const grid = ['#######', '#AAAAA#', '#ABBBB#', '#ABBBB#', '#######'];
    const state = createState({ grid, discoveredRooms: ['A'] });
    state.dungeon.layout.lights = [
      // Undiscovered room B cell: not rendered.
      createLight({ position: { x: 2, y: 2 } }),
      // Disabled: not rendered.
      createLight({ position: { x: 1, y: 2 }, enabled: false }),
    ];
    const ctx = createMockCtx();
    renderLights(ctx, CELL_SIZE, state, false);
    expect(ctx.createRadialGradient).not.toHaveBeenCalled();
  });

  it('renders undiscovered lights in debug mode', () => {
    const grid = ['#######', '#AAAAA#', '#ABBBB#', '#ABBBB#', '#######'];
    const state = createState({ grid, discoveredRooms: ['A'] });
    state.dungeon.layout.lights = [createLight({ position: { x: 2, y: 2 } })];
    const ctx = createMockCtx();
    renderLights(ctx, CELL_SIZE, state, true);
    expect(ctx.createRadialGradient).toHaveBeenCalled();
  });

  it('renders nothing when there are no lights', () => {
    const state = createState();
    const ctx = createMockCtx();
    renderLights(ctx, CELL_SIZE, state, false);
    expect(ctx.createRadialGradient).not.toHaveBeenCalled();
  });

  it('softens a light edges with a blur filter when softness is set', () => {
    const state = createState();
    state.dungeon.layout.lights = [createLight({ softness: 0.5 })];
    const ctx = createMockCtx();
    const filters: (string | undefined)[] = [];
    Object.defineProperty(ctx, 'filter', {
      get: () => filters[filters.length - 1],
      set: (value: string) => filters.push(value),
    });
    renderLights(ctx, CELL_SIZE, state, false);
    // softness 0.5 => half a cell of blur: 0.5 * 48 / 2 = 12px.
    expect(filters).toContain('blur(12px)');
    // The filter is reset after drawing.
    expect(filters[filters.length - 1]).toBe('none');
  });

  it('keeps hard edges when softness is 0', () => {
    const state = createState();
    state.dungeon.layout.lights = [createLight({ softness: 0 })];
    const ctx = createMockCtx();
    const filters: (string | undefined)[] = [];
    Object.defineProperty(ctx, 'filter', {
      get: () => filters[filters.length - 1],
      set: (value: string) => filters.push(value),
    });
    renderLights(ctx, CELL_SIZE, state, false);
    expect(filters).toEqual(['none']);
  });

  it('maps softness to a blur radius with clamping and a default', () => {
    expect(lightBlurPx(createLight({ softness: 0 }), CELL_SIZE)).toBe(0);
    expect(lightBlurPx(createLight({ softness: 0.5 }), CELL_SIZE)).toBe(12);
    // 1 (and anything above) = half a cell of blur.
    expect(lightBlurPx(createLight({ softness: 1 }), CELL_SIZE)).toBe(24);
    expect(lightBlurPx(createLight({ softness: 2 }), CELL_SIZE)).toBe(24);
    // Default softness is 0.25.
    expect(lightBlurPx(createLight({ softness: undefined }), CELL_SIZE)).toBe(
      6,
    );
  });
});

describe('renderAmbientDarkness', () => {
  const createMockCtx = () =>
    ({
      createRadialGradient: vi.fn().mockReturnValue({ addColorStop: vi.fn() }),
      save: vi.fn(),
      restore: vi.fn(),
      beginPath: vi.fn(),
      moveTo: vi.fn(),
      lineTo: vi.fn(),
      closePath: vi.fn(),
      fill: vi.fn(),
      arc: vi.fn(),
      stroke: vi.fn(),
      drawImage: vi.fn(),
      setTransform: vi.fn(),
      clearRect: vi.fn(),
      fillRect: vi.fn(),
    }) as unknown as CanvasRenderingContext2D;

  const createDarknessCanvas = (ctx: CanvasRenderingContext2D) =>
    ({
      width: 800,
      height: 600,
      getContext: () => ctx,
    }) as unknown as HTMLCanvasElement;

  it('derives the ambient light level with clamping and a default of 1', () => {
    expect(ambientLightLevel(createState())).toBe(1);
    const dark = createState();
    dark.dungeon.ambientLight = 0.25;
    expect(ambientLightLevel(dark)).toBe(0.25);
    const overflow = createState();
    overflow.dungeon.ambientLight = 2;
    expect(ambientLightLevel(overflow)).toBe(1);
    const negative = createState();
    negative.dungeon.ambientLight = -0.5;
    expect(ambientLightLevel(negative)).toBe(0);
  });

  it('is a no-op at full ambient light', () => {
    const state = createState();
    state.dungeon.layout.lights = [createLight()];
    const ctx = createMockCtx();
    const darknessCtx = createMockCtx();
    renderAmbientDarkness(
      ctx,
      createDarknessCanvas(darknessCtx),
      CELL_SIZE,
      state,
      false,
    );
    expect(darknessCtx.fillRect).not.toHaveBeenCalled();
    expect(ctx.drawImage).not.toHaveBeenCalled();
  });

  it('veils the view and punches holes for visible lights', () => {
    const state = createState();
    state.dungeon.ambientLight = 0.2;
    state.dungeon.layout.lights = [createLight()];
    const ctx = createMockCtx();
    const darknessCtx = createMockCtx();
    const fillStyles: string[] = [];
    Object.defineProperty(darknessCtx, 'fillStyle', {
      get: () => fillStyles[fillStyles.length - 1],
      set: (value: string) => fillStyles.push(value),
    });
    renderAmbientDarkness(
      ctx,
      createDarknessCanvas(darknessCtx),
      CELL_SIZE,
      state,
      false,
    );
    // Darkness veil at (1 - ambientLight), then the light's gradient.
    expect(fillStyles[0]).toBe('rgba(0, 0, 0, 0.8)');
    expect(darknessCtx.fillRect).toHaveBeenCalled();
    // Hole punched for the light, then composite operation restored.
    expect(darknessCtx.globalCompositeOperation).toBe('source-over');
    expect(darknessCtx.fill).toHaveBeenCalled();
    // Darkness composited over the scene.
    expect(ctx.drawImage).toHaveBeenCalled();
  });

  it('does not punch holes for disabled or undiscovered lights', () => {
    const grid = ['#######', '#AAAAA#', '#ABBBB#', '#ABBBB#', '#######'];
    const state = createState({ grid, discoveredRooms: ['A'] });
    state.dungeon.ambientLight = 0.2;
    state.dungeon.layout.lights = [
      createLight({ position: { x: 2, y: 2 } }),
      createLight({ position: { x: 1, y: 2 }, enabled: false }),
    ];
    const ctx = createMockCtx();
    const darknessCtx = createMockCtx();
    renderAmbientDarkness(
      ctx,
      createDarknessCanvas(darknessCtx),
      CELL_SIZE,
      state,
      false,
    );
    expect(darknessCtx.fillRect).toHaveBeenCalled();
    expect(darknessCtx.createRadialGradient).not.toHaveBeenCalled();
    expect(darknessCtx.fill).not.toHaveBeenCalled();
    expect(ctx.drawImage).toHaveBeenCalled();
  });
});
